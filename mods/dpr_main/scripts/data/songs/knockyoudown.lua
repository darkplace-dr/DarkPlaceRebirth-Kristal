local function setPerformerAnimation(time, performer, animation, round_to_beat, beats)
    return {
		type = "function",
        time = round_to_beat and roundToBeat(time or 0, _bpm, beats) or (time or 0),
		triggered = false,
		callback = function()
			if Game.minigame then
